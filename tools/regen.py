def load_manifest() -> dict:
    return tomllib.loads(MANIFEST.read_text())


def calls(func: dict):
    for key in ("call", "call_ncp", "call_mu"):
        c = func.get(key)
        if c and "c_symbol" in c:
            yield key, c


def value_inputs(func: dict, call: dict) -> list[str]:
    """C double arguments (public names) for one call, in C order."""
    if func["kind"] in ("d", "p", "q"):
        return [func["params"][0]["py"], *call["c_args"]]
    return list(call["c_args"])


def ufunc_table(manifest: dict) -> dict[str, tuple[list[str], list[str]]]:
    """c_symbol -> (double input names, flag names)."""
    table: dict[str, tuple[list[str], list[str]]] = {}
    for f in manifest["func"]:
        for _, c in calls(f):
            sig = (value_inputs(f, c), list(f["flags"]))
            prev = table.get(c["c_symbol"])
            if prev is not None and prev != sig:
                raise SystemExit(f"inconsistent signatures for C symbol {c['c_symbol']}: {prev} vs {sig}")
            table[c["c_symbol"]] = sig
    for sym, sig in RAW_ONLY.items():
        table[sym] = sig
    return table


def rmath_prototypes() -> dict[str, tuple[int, int]]:
    """symbol -> (number of double args, number of int args) from Rmath.h."""
    protos: dict[str, tuple[int, int]] = {}
    pat = re.compile(r"^\s*double\s+(\w+)\s*\(([^)]*)\)\s*;", re.M)
    for m in pat.finditer(RMATH_H.read_text()):
        args = [a.strip() for a in m.group(2).split(",") if a.strip()]
        if any("*" in a for a in args):
            continue
        protos[m.group(1)] = (sum(a.startswith("double") for a in args), sum(a.startswith("int") for a in args))
    return protos


def validate(table: dict) -> None:
    protos = rmath_prototypes()
    for sym, (vals, flags) in table.items():
        if sym not in protos:
            raise SystemExit(f"{sym}: no scalar prototype in Rmath.h")
        nd, ni = protos[sym]
        if (nd, ni) != (len(vals), len(flags)):
            raise SystemExit(f"{sym}: Rmath.h has ({nd} double, {ni} int) but manifest gives {vals} + {flags}")


def flag_c_name(kind: str, flag: str) -> str:
    if flag == "lower_tail":
        return "lower_tail"
    return "give_log" if kind == "d" else "log_p"


