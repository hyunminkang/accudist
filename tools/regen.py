def render_docs(manifest: dict) -> str:
    funcs = manifest["func"]
    out = [HEADER_MD, "# API reference\n\n",
           "All functions accept scalars or array-likes and broadcast like NumPy ufuncs. ",
           "`lower_tail=False` selects R's direct upper-tail algorithm; `log=True` works on the log scale for `d`, `p` and `q` alike.\n\n",
           "## Distributions\n\n| accudist | R | notes |\n|---|---|---|\n"]
    for f in funcs:
        if f["kind"] not in "dpqr":
            continue
        notes = []
        if f.get("dispatch") == "ncp":
            notes.append("`ncp=None` -> central algorithm; any value -> non-central")
        if f.get("dispatch") == "prob_or_mu":
            notes.append("exactly one of `prob`, `mu`")
        if f.get("alias") == "rate_scale":
            notes.append("`rate` or `scale`, not both")
        if f.get("c_transform", {}).get("rate"):
            notes.append("C takes `scale = 1/rate`")
        if f["name"] in ("ptukey", "qtukey"):
            notes.append("C argument order differs from R's; handled internally")
        if f.get("cache"):
            notes.append("locked shared table; see `free_caches()`")
        if f["kind"] == "r":
            notes.append("not R's `set.seed()` stream")
        sig = f"`{f['name']}({', '.join(public_params(f))}{'' if f['kind'] == 'r' else ', *, out=None'})`"
        out.append(f"| {sig} | `{r_signature(f)}` | {'; '.join(notes)} |\n")
    out.append("\n## Special functions\n\nThese keep Rmath's C names, so `gammafn` sits unambiguously beside `dgamma`.\n\n| accudist | R | summary |\n|---|---|---|\n")
    for f in funcs:
        if f["kind"] == "special":
            out.append(f"| `{f['name']}({', '.join(public_params(f))})` | `{f.get('r_equivalent', '')}` | {f.get('summary', f.get('note', ''))} |\n")
    out.append("\n## Numerical utilities\n\n| accudist | summary |\n|---|---|\n")
    for f in funcs:
        if f["kind"] == "util":
            out.append(f"| `{f['name']}({', '.join(public_params(f))})` | {f.get('summary', '')} |\n")
    out.append("\n## Bespoke wrappers\n\n| accudist | C symbol | why not a plain ufunc |\n|---|---|---|\n")
    for b in manifest["bespoke"]:
        out.append(f"| `{b['name']}` | `{b['c_symbol']}` | {b['reason']} |\n")
    out.append("\n## RNG primitives\n\n| accudist | summary |\n|---|---|\n")
    for r in manifest["rng_primitive"]:
        out.append(f"| `{r['name']}` | {r['summary']} |\n")
    out.append("\n## Deliberately excluded `Rmath.h` symbols\n\n| symbol | reason |\n|---|---|\n")
    for e in manifest["excluded"]:
        out.append(f"| `{e['c_symbol']}` | {e['reason']} |\n")
    return "".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if any generated file is stale")
    args = ap.parse_args()

    manifest = load_manifest()
    table = ufunc_table(manifest)
    validate(table)
    rendered = {
        "c": render_c(manifest, table),
        "api": render_api(manifest),
        "rmath": render_rmath(table, manifest),
        "docs": render_docs(manifest),
    }
    stale = []
    for key, text in rendered.items():
        path = OUTPUTS[key]
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("stale generated files (run tools/regen.py):\n  " + "\n  ".join(stale), file=sys.stderr)
        return 1
    print(f"{len(table)} ufuncs, {len(manifest['func'])} public functions" + (" -- up to date" if args.check else ""))
    return 0


