def r_signature(f: dict) -> str:
    """R's own call signature for the docstring."""
    kind = f["kind"]
    parts = []
    for p in f["params"]:
        name = R_ARG_NAME.get(p["py"], p["py"])
        if f.get("alias") == "rate_scale" and name == "scale":
            parts.append("scale = 1/rate")
        elif "default" in p:
            d = p["default"]
            parts.append(f"{name} = {'TRUE' if d is True else 'FALSE' if d is False else int(d) if float(d).is_integer() else d}")
        else:
            parts.append(name)
    if f.get("dispatch") == "ncp":
        parts.append("ncp")
    if kind == "d":
        parts.append("log = FALSE")
    elif kind in ("p", "q"):
        parts += ["lower.tail = TRUE", "log.p = FALSE"]
    r_name = f.get("r_equivalent", "").split("(")[0] or f["name"]
    if kind in "dpqr":
        r_name = f["name"]
    return f"{r_name}({', '.join(parts)})"


def py_default(p: dict) -> str:
    if "default" not in p:
        return ""
    d = p["default"]
    if isinstance(d, bool):
        return f"={d}"
    return f"={d!r}"


def public_params(f: dict) -> list[str]:
    """Python parameter list (without flags / out)."""
    kind = f["kind"]
    ps = []
    for i, p in enumerate(f["params"]):
        name = p["py"]
        if f.get("alias") == "rate_scale" and name in ("rate", "scale"):
            ps.append(f"{name}=None")
        elif f.get("dispatch") == "prob_or_mu" and name in ("prob", "mu"):
            ps.append(f"{name}=None")
        else:
            ps.append(name + py_default(p))
    if f.get("dispatch") == "ncp":
        ps.append("ncp=None")
    if kind == "d":
        ps.append("log=False")
    elif kind in ("p", "q"):
        ps += ["lower_tail=True", "log=False"]
    return ps


def param_doc(f: dict, name: str) -> str:
    fam = f.get("family") or f["kind"]
    for key in ((fam, name), ("*", name), (f["kind"], name)):
        if key in PARAM_DOC:
            return PARAM_DOC[key]
    return ""


def docstring(f: dict) -> str:
    kind, name = f["kind"], f["name"]
    fam = f.get("family")
    if kind in "dpqr":
        ft = FAMILY_TITLE[fam]
        title = f"{ft[0].upper() + ft[1:]} {KIND_TITLE[kind]}."
    else:
        title = (f.get("summary") or f"``{f.get('r_equivalent', name)}`` from R.").rstrip(".") + "."
        title = title[0].upper() + title[1:]
    lines = [title, ""]
    lines.append(f"R equivalent: ``{r_signature(f)}``")
    if fam and f.get("r_page"):
        lines.append(f"(help page ``?{f['r_page']}``).")
    if f.get("note"):
        lines.append(f"Note: {f['note']}.")
    lines += ["", "Parameters", "----------"]
    if kind == "r":
        lines += [f"{f['params'][0]['py']} : int", "    Number of draws. Other parameters recycle to this length as in R."]
        params = f["params"][1:]
    else:
        params = f["params"]
    for p in params:
        pname = p["py"]
        lines.append(f"{pname} : array_like" + (", optional" if ("default" in p or pname in ("scale", "mu", "prob") and (f.get("alias") or f.get("dispatch"))) else ""))
        doc = param_doc(f, pname)
        if doc:
            lines.append(f"    {doc}")
    if f.get("dispatch") == "ncp":
        lines += ["ncp : array_like, optional", f"    {PARAM_DOC[('*', 'ncp')]}"]
    if kind in "dpq":
        if kind in "pq":
            lines += ["lower_tail : bool, default True", f"    {PARAM_DOC[('*', 'lower_tail')]}"]
        lines += ["log : bool, default False", f"    {PARAM_DOC[('*', 'log')]}"]
    if kind != "r":
        lines += ["out : ndarray, optional", "    Preallocated output array (passed to the underlying ufunc)."]
    lines += ["", "Returns", "-------"]
    if kind == "r":
        lines += ["ndarray", f"    ``float64`` array of length ``{f['params'][0]['py']}``, even for discrete distributions."]
        lines += ["", "Notes", "-----", f"{RNG_CAVEAT}"]
    else:
        lines += ["numpy.float64 or ndarray", "    Scalar inputs give a NumPy scalar; array inputs broadcast."]
        if kind == "q":
            lines += ["    Quantiles of discrete distributions are returned as doubles, as R does."]
    if f.get("cache"):
        lines += ["", "Notes", "-----",
                  "Uses a process-wide distribution table guarded by a lock; concurrent calls",
                  "serialise. Memory grows with the sample sizes; ``accudist.free_caches()`` releases it."]
    return "\n".join(lines)


def indent(text: str, n: int = 4) -> str:
    pad = " " * n
    return "\n".join(pad + ln if ln else "" for ln in text.splitlines())


def ufunc_call(f: dict, call: dict, var_map: dict[str, str], flags_expr: list[str], out: bool) -> str:
    args = [var_map.get(a, a) for a in value_inputs(f, call)] + flags_expr
    tail = ", out=out" if out else ""
    return f"_uf.{call['c_symbol']}({', '.join(args)}{tail})"


def render_dpq(f: dict) -> str:
    kind, name = f["kind"], f["name"]
    params = ", ".join(public_params(f))
    flags = ["lower_tail", "log"] if kind in "pq" else ["log"]
    body = []
    var_map: dict[str, str] = {}
    if f.get("c_transform"):
        for k, expr in f["c_transform"].items():
            if expr == "1.0 / rate":
                body.append(f"    {k} = _inv({k})")
            else:
                body.append(f"    {k} = {expr}")
    if f.get("alias") == "rate_scale":
        body.append(f"    scale = _resolve_rate_scale(rate, scale, {name!r})")
    lock = "_cache_lock" if f.get("cache") else None
    ind = "    "
    body.append(f"{ind}_clear()")
    if lock:
        body.append(f"{ind}with {lock}:")
        ind += "    "
    if f.get("dispatch") == "ncp":
        body.append(f"{ind}if ncp is None:")
        body.append(f"{ind}    r = {ufunc_call(f, f['call'], var_map, flags, True)}")
        body.append(f"{ind}else:")
        body.append(f"{ind}    r = {ufunc_call(f, f['call_ncp'], var_map, flags, True)}")
    elif f.get("dispatch") == "prob_or_mu":
        body.append(f"{ind}if _resolve_prob_mu(prob, mu, {name!r}):")
        body.append(f"{ind}    r = {ufunc_call(f, f['call_mu'], var_map, flags, True)}")
        body.append(f"{ind}else:")
        body.append(f"{ind}    r = {ufunc_call(f, f['call'], var_map, flags, True)}")
    else:
        body.append(f"{ind}r = {ufunc_call(f, f['call'], var_map, flags, True)}")
    body.append(f"    _check({name!r})")
    body.append("    return r")
    return (
        f"\n\ndef {name}({params}, *, out=None):\n"
        f'    """\n{indent(docstring(f))}\n    """\n' + "\n".join(body) + "\n"
    )


def render_special(f: dict) -> str:
    name = f["name"]
    params = ", ".join(public_params(f))
    body = []
    for k, expr in (f.get("c_transform") or {}).items():
        body.append(f"    {k} = {expr}")
    body.append("    _clear()")
    body.append(f"    r = {ufunc_call(f, f['call'], {}, [], True)}")
    body.append(f"    _check({name!r})")
    body.append("    return r")
    return (
        f"\n\ndef {name}({params}, *, out=None):\n"
        f'    """\n{indent(docstring(f))}\n    """\n' + "\n".join(body) + "\n"
    )


def render_r(f: dict) -> tuple[str, str, str]:
    """Returns (impl function, module-level function, RNG method)."""
    name = f["name"]
    count = f["params"][0]["py"]
    params = public_params(f)
    sig = ", ".join(params)
    arg_names = [p.split("=")[0] for p in params]
    fwd = ", ".join(arg_names)
    body = [f"    {count} = _draw_count({count})"]
    var_map: dict[str, str] = {}
    for k, expr in (f.get("c_transform") or {}).items():
        body.append(f"    {k} = _inv({k})" if expr == "1.0 / rate" else f"    {k} = {expr}")
    if f.get("alias") == "rate_scale":
        body.append(f"    scale = _resolve_rate_scale(rate, scale, {name!r})")

    def rec(call: dict) -> str:
        args = ", ".join(f"_recycle({a}, {count}, {a!r})" for a in call["c_args"])
        return f"rng._draw({name!r}, _uf.{call['c_symbol']}, ({args},))"

    if f.get("dispatch") == "ncp":
        body.append("    if ncp is None:")
        body.append(f"        return {rec(f['call'])}")
        if "c_symbol" in f["call_ncp"]:
            body.append(f"    return {rec(f['call_ncp'])}")
        else:
            body.append("    with _rng_lock:  # composed draw is atomic w.r.t. other threads")
            body.append(indent(COMPOSED[name].rstrip("\n"), 4))
    elif f.get("dispatch") == "prob_or_mu":
        body.append(f"    if _resolve_prob_mu(prob, mu, {name!r}):")
        body.append(f"        return {rec(f['call_mu'])}")
        body.append(f"    return {rec(f['call'])}")
    else:
        body.append(f"    return {rec(f['call'])}")
    impl = f"\n\ndef _{name}(rng, {sig}):\n" + "\n".join(body) + "\n"
    doc = f'    """\n{indent(docstring(f))}\n    """\n'
    public = f"\n\ndef {name}({sig}):\n{doc}    return _{name}(_default_rng, {fwd})\n"
    method = (
        f"\n    def {name}(self, {sig}):\n"
        f'        """{KIND_TITLE["r"].capitalize()} for the {FAMILY_TITLE[f["family"]]} distribution on this stream; see :func:`accudist.{name}`."""\n'
        f"        return _{name}(self, {fwd})\n"
    )
