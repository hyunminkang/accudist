def render_c(manifest: dict, table: dict) -> str:
    kind_of = {c["c_symbol"]: f["kind"] for f in manifest["func"] for _, c in calls(f)}
    out = [HEADER_C, '''
#define PY_SSIZE_T_CLEAN
#include <Python.h>
#define NPY_NO_DEPRECATED_API NPY_1_25_API_VERSION
/* share the NumPy C-API tables imported by _ufuncsmodule.c */
#define PY_ARRAY_UNIQUE_SYMBOL accudist_ARRAY_API
#define PY_UFUNC_UNIQUE_SYMBOL accudist_UFUNC_API
#define NO_IMPORT_ARRAY
#define NO_IMPORT_UFUNC
#include <numpy/arrayobject.h>
#include <numpy/ufuncobject.h>
#include <fenv.h>
#include <math.h>
#include <Rmath.h>

#define D(p) (*(double *)(p))
#define FLAG(p) ((int)(*(double *)(p) != 0.0))

static void *no_data[1] = {NULL};
''']
    regs = []
    for sym, (vals, flags) in table.items():
        nin = len(vals) + len(flags)
        ptrs = ", ".join(f"*a{i} = args[{i}]" for i in range(nin))
        call_args = ", ".join([f"D(a{i})" for i in range(len(vals))] + [f"FLAG(a{len(vals) + j})" for j in range(len(flags))])
        steps = " ".join(f"a{i} += steps[{i}];" for i in range(nin))
        kind = kind_of.get(sym, "special")
        if kind == "r":
            body = f"D(o) = {sym}({call_args});"
        else:
            # R's own wrappers (arithmetic.c math1..math4) return NaN when any
            # argument is NaN *before* calling nmath; a few nmath entry points
            # (pnt, ...) would otherwise return a finite value. Mirror that.
            nan_test = " || ".join(f"isnan(D(a{i}))" for i in range(len(vals)))
            nan_val = " + ".join(f"D(a{i})" for i in range(len(vals)))
            body = f"D(o) = ({nan_test}) ? ({nan_val}) : {sym}({call_args});"
        out.append(f'''
static void {sym}_loop(char **args, npy_intp const *dims, npy_intp const *steps, void *data)
{{
    npy_intp n = dims[0];
    char {ptrs}, *o = args[{nin}];
    for (npy_intp i = 0; i < n; i++) {{
        {body}
        {steps} o += steps[{nin}];
    }}
    /* nmath computes with Inf/NaN deliberately (R never warns about FP flags);
       discard the status so NumPy does not raise spurious RuntimeWarnings. */
    feclearexcept(FE_ALL_EXCEPT);
}}
static PyUFuncGenericFunction {sym}_funcs[1] = {{&{sym}_loop}};
static char {sym}_types[{nin + 1}] = {{{", ".join(["NPY_DOUBLE"] * (nin + 1))}}};
''')
        doc_args = ", ".join(vals + [flag_c_name(kind, fl) for fl in flags])
        regs.append(
            f'    ADD("{sym}", {sym}_funcs, {sym}_types, {nin}, "{sym}({doc_args}) -> double  [C: {sym}]");'
        )
    out.append('''
#define ADD(name, funcs, types, nin, doc)                                          \\
    do {                                                                            \\
        PyObject *f = PyUFunc_FromFuncAndData(funcs, no_data, types, 1, nin, 1,     \\
                                              PyUFunc_None, name, doc, 0);          \\
        if (f == NULL || PyModule_AddObject(m, name, f) < 0) {                      \\
            Py_XDECREF(f);                                                          \\
            return -1;                                                              \\
        }                                                                           \\
    } while (0)

int accudist_add_generated_ufuncs(PyObject *m)
{
''')
    out.extend(r + "\n" for r in regs)
    out.append("    return 0;\n}\n")
    return "".join(out)


